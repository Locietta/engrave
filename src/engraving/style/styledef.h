using StyleId = Sid;
using StyleIdSet = std::unordered_set<Sid>;

//---------------------------------------------------------
//   StyledProperty
///   \cond PLUGIN_API \private \endcond
//---------------------------------------------------------
struct StyledProperty {
    Sid sid;
    Pid pid;
};

typedef std::vector<StyledProperty> ElementStyle;

//---------------------------------------------------------
//   StyleDef
///   \cond PLUGIN_API \private \endcond
//---------------------------------------------------------
struct StyleDef {
public:
    struct StyleValue {
        Sid sid{Sid::NOSTYLE};
        muse::AsciiStringView xml_name;
        PropertyValue default_value;

        inline size_t idx() const { return size_t(sid); }

        inline PType value_type() const { return default_value.type(); }
    };

    static const std::array<StyleValue, size_t(Sid::STYLES)> style_values;

    static double default_smufl_point_size() {
        const double default_spatium = ::mu::engraving::StyleDef::style_values[static_cast<size_t>(Sid::SPATIUM)].default_value.to_double();
        const double default_spatium_in_point_units = default_spatium / mu::engraving::dpi * mu::engraving::ppi;
        const double default_smufl_point_size = 4 * default_spatium_in_point_units; // By Smufl spec the spatium is 1/4 of the em

        return default_smufl_point_size;
    }
};
