void set_warning_identity_test_fault(ExportWarning warning) { warning_identity_test_fault = std::move(warning); }

Result<ExportOutput> export_score(const music::EngineContext &context, const music::ScoreProject &project, Score &score,
                                  const std::string &format, const music::ExportOptions &options) try {
    std::vector<ExportWarning> warnings;
    if (warning_identity_test_fault) {
        warnings.push_back(std::move(*warning_identity_test_fault));
        warning_identity_test_fault.reset();
        normalize_warnings(warnings);
    }
    const auto score_id = score.eid().is_valid() ? std::optional(from_engine(score.eid())) : std::nullopt;
    auto &master = *score.master_score();
    std::vector<Score *> source_scores{&score};
    if (score.is_master())
        for (auto *excerpt : master.excerpts())
            if (excerpt->excerpt_score()) source_scores.push_back(excerpt->excerpt_score());
    // Warning locators use document order even for a standalone selection.
    std::vector<Score *> document_scores{&master};
    for (auto *excerpt : master.excerpts())
        if (excerpt->excerpt_score()) document_scores.push_back(excerpt->excerpt_score());
    for (auto *item : document_objects(master)) {
        poll();
        if (!item->is_note()) continue;
        if (std::find(source_scores.begin(), source_scores.end(), static_cast<Note *>(item)->score()) == source_scores.end()) continue;
        auto *tie = static_cast<Note *>(item)->tie_for();
        if (tie && tie->start_note() && tie->end_note() && tie->start_note()->ppitch() != tie->end_note()->ppitch()) {
            auto *note = static_cast<Note *>(item);
            const auto score_index = std::find(document_scores.begin(), document_scores.end(), note->score()) - document_scores.begin();
            std::size_t measure_index = 0;
            for (auto *measure = note->score()->first_measure(); measure && measure != note->chord()->measure();
                 measure = measure->next_measure())
                ++measure_index;
            const auto &notes = note->chord()->notes();
            ExportWarningObject identity{
                "tie", "locator:score:" + std::to_string(score_index) + "/measure:" + std::to_string(measure_index) +
                           "/tick:" + std::to_string(note->tick().ticks()) + "/track:" + std::to_string(note->track()) +
                           "/note:" + std::to_string(std::find(notes.begin(), notes.end(), note) - notes.begin()) + "/tieFor"};
            if (tie->eid().is_valid())
                identity = {"tie", tie->eid().to_std_string()};
            else {
                // A tie need not have an EID. Name its nearest addressable owner,
                // never stringify the invalid-EID sentinel as a real handle.
                for (auto *owner = item; owner; owner = owner->parent()) {
                    if (owner->eid().is_valid()) {
                        std::string kind = owner->type_name();
                        std::transform(kind.begin(), kind.end(), kind.begin(),
                                       [](char c) { return c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c; });
                        identity = {std::move(kind), to_string(from_engine(owner->eid()))};
                        break;
                    }
                }
            }
            warnings.push_back({"B470_INVALID_TIE", "Cannot write 4.70: tied notes have different pitches.", std::move(identity)});
        }
    }
    if (!warnings.empty()) return refused(std::move(warnings));
    if (master.chord_list()->custom_chord_list() && !master.chord_list()->empty())
        warnings.push_back({"B470_UNSUPPORTED_FEATURE", "4.70 conversion of a custom chord list is not implemented", score_id});
    if (const auto automation = master.automation_data()) {
        for ([[maybe_unused]] const auto &[key, curve] : automation->curves()) {
            if (std::any_of(curve.begin(), curve.end(), [](const auto &point) { return !point.second.generated; }))
                warnings.push_back({"B470_UNSUPPORTED_FEATURE", "4.70 cannot represent this automation curve", score_id});
        }
    }

    // The 5.00 serializer supplies the current DOM values. It is only an
    // intermediate: the checked subset is converted to the 4.70 structure.
    // Its XML is working data, not the output, so do not apply the output cap.
    auto *budget = muse::io::active_write_budget;

    struct RestoreOutputLimit {
        muse::io::WriteBudget *budget;
        std::optional<std::uint64_t> limit;

        ~RestoreOutputLimit() {
            if (budget) budget->output = limit;
        }
    } restore{budget, budget ? budget->output : std::nullopt};

    if (budget) budget->output.reset();
    const std::string source = music::export_native_score(context, project, "mscx", options, {});
    if (budget) budget->output = restore.limit;

    struct ProgressScope {
        testing::Write470Progress previous = testing::progress;

        ProgressScope() { testing::progress = {testing::Write470Progress::Stage::CONVERTING}; }

        ~ProgressScope() { testing::progress = previous; }
    } progress_scope;

    poll();
    charge_xml(source.size());
    pugi::xml_document xml;
    if (!xml.load_buffer(source.data(), source.size(), pugi::parse_default | pugi::parse_ws_pcdata))
        throw std::runtime_error("could not parse the engine's score output");
    auto root = xml.child("museScore");
    auto score_node = root.child("Score");
    if (!root || !score_node) throw std::runtime_error("engine output has no score");
    remove_xml_indentation(root);
    std::vector<ExportWarning> degraded;
    convert_degradations(root, master, degraded);
    for (const auto *source_score : source_scores) warn_active_instrument_groups(*source_score, degraded);
    std::vector<pugi::xml_node> score_nodes{score_node};
    for (std::size_t i = 0; i < score_nodes.size(); ++i)
        for (auto excerpt : score_nodes[i].children("Score")) score_nodes.push_back(excerpt);
    if (source_scores.size() != score_nodes.size()) throw std::runtime_error("excerpt count changed during serialization");
    for (std::size_t index = 0; index < score_nodes.size(); ++index) strip_neutral_masks(score_nodes[index], *source_scores[index]);
    auto connector_issues = reconstruct_connectors(root, source_scores, poll);
    for (auto &[node, detail] : connector_issues) {
        auto owner = node;
        while (owner && std::string_view(owner.name()) != "Score") owner = owner.parent();
        unsupported(node, std::move(detail), owner ? node_id(owner) : score_id, warnings);
    }
    if (!connector_issues.empty()) {
        warnings.insert(warnings.begin(), degraded.begin(), degraded.end());
        return refused(std::move(warnings));
    }
    ParenthesisAliases aliases;
    for (std::size_t index = 0; index < score_nodes.size(); ++index) {
        auto current = score_nodes[index];
        auto &source_score = *source_scores[index];
        const auto current_id = source_score.eid().is_valid() ? std::optional(from_engine(source_score.eid())) : score_id;
        ScoreFeatures features;
        auto source_part = source_score.parts().begin();
        for (auto part : current.children("Part")) {
            poll();
            if (source_part == source_score.parts().end()) throw std::runtime_error("part count changed during serialization");
            const auto &part_dom = **source_part++;
            const auto *instrument = part_dom.instrument();
            features.grand_staff |= part_dom.nstaves() > 1;
            features.vocal_staves |= instrument->group() == "vocals";
            features.names |= !instrument->instrument_label().empty();
            for (const auto *staff : part_dom.staves()) {
                const auto *type = staff->staff_type(mu::engraving::Fraction(0, 1));
                features.names |= !type->staff_label().empty();
                const auto visibility = type->instrument_label_visibility();
                features.force_names |= visibility == InstrumentLabelVisibility::LONG || visibility == InstrumentLabelVisibility::SHORT;
            }
            auto first_instrument = part.child("Instrument");
            if (!first_instrument) throw std::runtime_error("serialized part has no instrument");
            convert_instrument(first_instrument, *instrument, part_dom, mu::engraving::Fraction(0, 1), current_id, warnings);
            auto legacy_track_name = part.insert_child_before("trackName", first_instrument);
            legacy_track_name.text().set(part_dom.part_name().to_std_string().c_str());
        }
        if (source_part != source_score.parts().end()) throw std::runtime_error("part count changed during serialization");
        convert_notation(current, source_score, current_id, features, aliases, warnings);
        convert_style(current, source_score, current_id, features, warnings);
        for (auto part : current.children("Part")) part.remove_child("eid");
    }
    if (!aliases.empty()) rebase_parenthesis_links(root, aliases);
    for (auto child : root.children()) {
        if (child.type() == pugi::node_element && !allowed_child(root, child.name())) unsupported(child, child.name(), score_id, warnings);
    }
    if (!warnings.empty()) {
        warnings.insert(warnings.begin(), degraded.begin(), degraded.end());
        return refused(std::move(warnings));
    }

    warnings = std::move(degraded);
    normalize_warnings(warnings);
    root.attribute("version").set_value("4.70");

    muse::ByteArray xml_data;
    // For MSCX this is the final output, so enforce its cap as it grows. For
    // MSCZ the XML is an intermediate and only the compressed archive is capped.
    OutputBuffer xml_buffer(&xml_data, format == "mscx");
    xml_buffer.open(muse::io::IODevice::WRITE_ONLY);
    XmlOutput writer(xml_buffer);
    testing::progress = {testing::Write470Progress::Stage::SERIALIZING};
    xml.save(writer, "  ", pugi::format_default, pugi::encoding_utf8);
    xml_buffer.close();
    muse::ByteArray data;
    if (format == "mscx") {
        if (budget && !budget->output_size(xml_data.size())) throw muse::io::WriteBudgetStop{};
        data = std::move(xml_data);
    } else {
        OutputBuffer output(&data);
        output.open(muse::io::IODevice::WRITE_ONLY);
        MscWriter::Params params;
        params.device = &output;
        params.main_file_name = u"score.mscx";
        MscWriter archive(params);
        if (!archive.open()) throw std::runtime_error("could not open 4.70 archive writer");
        archive.write_score_file(xml_data);
        archive.close();
        if (archive.has_error()) throw std::runtime_error("could not write 4.70 archive");
        output.close();
    }
    const auto *first = reinterpret_cast<const std::byte *>(data.const_data());
    return ExportOutput{std::vector<std::byte>(first, first + data.size()), std::move(warnings)};
} catch (const std::invalid_argument &error) {
    return std::unexpected(Error{ErrorCode::INVALID_ARGUMENT, error.what()});
}

