void unsupported(pugi::xml_node node, std::string detail, std::optional<ElementId> score_id, std::vector<ExportWarning> &warnings) {
    warnings.push_back(
        {"B470_UNSUPPORTED_FEATURE", "4.70 conversion is not implemented for " + std::move(detail), source_object(node, score_id)});
}

const EngravingObject *source_item(pugi::xml_node node, const Score &score) {
    if (const auto eid = node_id(node)) return score.master_score()->eid_register()->item_from_eid(to_engine(*eid));
    return nullptr;
}

void convert_bracket(pugi::xml_node bracket, std::optional<ElementId> score_id, std::vector<ExportWarning> &warnings) {
    constexpr std::array types{"Normal"sv, "Brace"sv, "Square"sv, "Line"sv};
    const auto type = std::find(types.begin(), types.end(), bracket.child_value("type"));
    if (type == types.end()) {
        unsupported(bracket, "BracketItem/type", score_id, warnings);
        return;
    }
    auto staff = bracket.parent();
    auto legacy = staff.insert_child_before("bracket", bracket);
    legacy.append_attribute("type") = static_cast<int>(type - types.begin());
    legacy.append_attribute("span") = bracket.child_value("bracketSpan");
    legacy.append_attribute("col") = bracket.child_value("level");
    legacy.append_attribute("visible") = bracket.child("visible") ? bracket.child_value("visible") : "1";
    staff.remove_child(bracket);
}

using ParenthesisAliases = ankerl::unordered_dense::map<std::string, pugi::xml_node>;

bool same_xml(pugi::xml_node left, pugi::xml_node right) {
    poll();
    return std::string_view(left.name()) == right.name() && std::string_view(left.value()) == right.value() &&
           std::ranges::equal(
               left.attributes(), right.attributes(),
               [](auto a, auto b) { return std::string_view(a.name()) == b.name() && std::string_view(a.value()) == b.value(); }) &&
           std::ranges::equal(left.children(), right.children(), same_xml);
}

void merge_parentheses(pugi::xml_node kept, pugi::xml_node duplicate, ParenthesisAliases &aliases, std::optional<ElementId> score_id,
                       std::vector<ExportWarning> &warnings) {
    for (auto paren : duplicate.children("Parenthesis")) {
        poll();
        const auto direction = [](pugi::xml_node node) { return std::string_view(node.child_value("horizontalDirection")) == "right"; };
        auto existing = kept.find_child(
            [&](pugi::xml_node node) { return std::string_view(node.name()) == "Parenthesis" && direction(node) == direction(paren); });
        if (!existing) {
            kept.insert_copy_before(paren, kept.child("Notes"));
            continue;
        }
        for (auto field : paren.children()) {
            poll();
            if (field.type() != pugi::node_element) continue;
            auto original = existing.child(field.name());
            if (!original)
                existing.append_copy(field);
            else if (std::string_view(field.name()) == "eid")
                aliases.emplace(field.child_value(), existing);
            else if (!same_xml(original, field))
                unsupported(paren, "duplicate NoteParenGroup with conflicting parenthesis properties", score_id, warnings);
        }
    }
}

void convert_note_indices(pugi::xml_node chord, const Score &score, std::optional<ElementId> score_id, ParenthesisAliases &aliases,
                          std::vector<ExportWarning> &warnings) {
    const auto *object = source_item(chord, score);
    const auto *source = object && object->is_chord() ? static_cast<const Chord *>(object) : nullptr;
    if (!source) {
        unsupported(chord, "NoteParenGroup without a source chord", score_id, warnings);
        return;
    }
    auto notes = legacy_notes(chord, *source, poll);
    sort_legacy_percussion_notes(notes, *source, poll);

    struct Group {
        pugi::xml_node xml;
        std::vector<std::size_t> members;
    };

    std::vector<Group> groups;
    std::vector<std::size_t> covering(notes.size(), 0);
    for (auto group = chord.child("NoteParenGroup"); group;) {
        const auto next = group.next_sibling("NoteParenGroup");
        std::vector<std::size_t> members;
        for (auto note : group.child("Notes").children("NoteEID")) {
            poll();
            const std::string_view eid = note.child_value();
            const auto found = std::find_if(notes.begin(), notes.end(), [&](const LegacyNote &entry) {
                poll();
                return entry.xml.child_value("eid") == eid;
            });
            if (found == notes.end()) {
                unsupported(group, "NoteParenGroup/NoteEID", score_id, warnings);
                continue;
            }
            const auto index = static_cast<std::size_t>(found - notes.begin());
            members.push_back(index);
            note.set_name("NoteIdx");
            note.text().set(index);
        }
        std::sort(members.begin(), members.end());
        members.erase(std::unique(members.begin(), members.end()), members.end());
        const auto existing = std::find_if(members.begin(), members.end(), [&](std::size_t index) { return covering[index] != 0; });
        if (members.empty()) {
            unsupported(group, "empty NoteParenGroup", score_id, warnings);
        } else if (existing == members.end()) {
            for (auto index : members) covering[index] = groups.size() + 1;
            groups.push_back({group, std::move(members)});
        } else if (const auto &kept = groups[covering[*existing] - 1]; kept.members == members) {
            merge_parentheses(kept.xml, group, aliases, score_id, warnings);
            chord.remove_child(group);
        } else {
            unsupported(group, "overlapping NoteParenGroups with different note sets", score_id, warnings);
        }
        group = next;
    }
}

void rebase_parenthesis_links(pugi::xml_node node, const ParenthesisAliases &aliases) {
    poll();
    for (auto child = node.first_child(); child;) {
        const auto next = child.next_sibling();
        if (std::string_view(child.name()) == "linkedTo") {
            if (const auto found = aliases.find(child.child_value()); found != aliases.end()) {
                if (found->second == node)
                    node.remove_child(child);
                else
                    child.text().set(found->second.child_value("eid"));
            }
        } else if (child.type() == pugi::node_element) {
            rebase_parenthesis_links(child, aliases);
        }
        child = next;
    }
}

bool neutral_mask(pugi::xml_node field, const Score &score) {
    if (std::string_view(field.child_value()) == "auto") return true;
    const Sid sid = std::string_view(field.parent().name()) == "Slur" ? Sid::MASK_SLURS : Sid::MASK_TIES;
    return std::string_view(field.child_value()) == "off" && !score.style().style_b(sid);
}

void strip_neutral_masks(pugi::xml_node node, const Score &score) {
    poll();
    if (auto field = node.child("maskSlurTie"); field && neutral_mask(field, score)) node.remove_child(field);
    for (auto child : node.children()) {
        if (child.type() == pugi::node_element && std::string_view(child.name()) != "Score") strip_neutral_masks(child, score);
    }
}

void write_name(pugi::xml_node instrument, pugi::xml_node before, const char *tag, String name, int pos) {
    if (name.empty()) return;
    name.replace(u"\n", u"<br/>");
    const auto value = name.to_std_string();
    auto legacy = instrument.insert_child_before(tag, before);
    if (pos) legacy.append_attribute("pos") = pos;
    if (!legacy.append_buffer(value.data(), value.size(), pugi::parse_default | pugi::parse_fragment | pugi::parse_ws_pcdata))
        throw std::runtime_error("invalid instrument label XML");
}

void convert_instrument(pugi::xml_node xml, const Instrument &instrument, const Part &part, const mu::engraving::Fraction &tick,
                        std::optional<ElementId> score_id, std::vector<ExportWarning> &warnings) {
    auto label = xml.child("InstrumentLabel");
    if (!label) label = xml.prepend_child("InstrumentLabel");
    const auto &style = part.score()->style();
    const auto &staves = part.staves();
    const bool hide_auto =
        style.style_b(Sid::HIDE_INSTRUMENT_NAME_IF_ONE_INSTRUMENT) && part.score()->visible_part_count() <= 1 && !part.is_shared_part();
    const auto hidden = [&](InstrumentLabelVisibility visibility) {
        return visibility == InstrumentLabelVisibility::HIDE ||
               (visibility == InstrumentLabelVisibility::AUTO && hide_auto &&
                std::any_of(staves.begin(), staves.end(), [&](const Staff *staff) {
                    const auto forced = staff->staff_type(tick)->instrument_label_visibility();
                    return forced == InstrumentLabelVisibility::LONG || forced == InstrumentLabelVisibility::SHORT;
                }));
    };
    for (const bool long_name : {true, false}) {
        const char *tag = long_name ? "longName" : "shortName";
        const auto name_type = long_name ? InstrumentLabelVisibility::LONG : InstrumentLabelVisibility::SHORT;
        const auto primary_visibility =
            staves.empty() ? InstrumentLabelVisibility::AUTO : staves.front()->staff_type(tick)->instrument_label_visibility();
        if (!hidden(primary_visibility)) {
            const bool use_long =
                primary_visibility == InstrumentLabelVisibility::AUTO ? long_name : primary_visibility == InstrumentLabelVisibility::LONG;
            auto value = rendering::score::SystemHeaderLayout::formatted_instrument_name(instrument, style, use_long);
            const auto base_name = use_long ? instrument.long_name() : instrument.short_name();
            const auto original = label.child(use_long ? "longName" : "shortName");
            if (original && value == base_name) {
                xml.insert_copy_before(original, label).set_name(tag);
            } else {
                write_name(xml, label, tag, std::move(value), original.attribute("pos").as_int());
            }
        }
        for (std::size_t index = 0; index < staves.size(); ++index) {
            poll();
            const auto *staff_type = staves[index]->staff_type(tick);
            const auto visibility = staff_type->instrument_label_visibility();
            if (hidden(visibility)) continue;
            const auto &staff_label = staff_type->staff_label();
            const auto &value =
                (visibility == InstrumentLabelVisibility::AUTO ? name_type : visibility) == InstrumentLabelVisibility::LONG ?
                    staff_label.long_name() :
                    staff_label.short_name();
            // The legacy layout defines individual placements for the first three staves.
            if (index < 3)
                write_name(xml, label, tag, value, static_cast<int>(2 * index + 1));
            else if (!value.empty())
                unsupported(xml, "StaffLabel position", score_id, warnings);
        }
    }
    xml.remove_child(label);
}

struct ScoreFeatures {
    bool lyrics = false;
    bool slurs = false;
    bool ties = false;
    bool dynamics = false;
    bool dashed_bars = false;
    bool grand_staff = false;
    bool vocal_staves = false;
    bool names = false;
    bool force_names = false;
};

bool five_only_style_is_inactive(std::string_view name, const ScoreFeatures &features, const MStyle &style) {
    // These styles configure features already projected by the part, bracket,
    // and label conversions.
    if (name.starts_with("groupBracket") || name.starts_with("staveSharing") || name.starts_with("sharedOnStaff") ||
        name.starts_with("unisonLabel") ||
        one_of(name, {"allowVoiceCrossing", "enableStaveSharing", "textForUnisonLabel", "windsNameByGroup", "vocalsNameByGroup",
                      "stringsNameByGroup", "othersNameByGroup", "instrumentNamesAlignIncludeGroupBrackets",
                      "instrumentNumeralsTrailingDotSingle"}) ||
        name.starts_with("instrumentNamesFormat") || name.starts_with("instrumentNamesCustomFormat") ||
        name.starts_with("instrumentNamesShowTransposition"))
        return true;
    if (name.starts_with("instrumentNumerals")) return true;
    if (name.starts_with("instrumentNames")) return !features.names;
    if (name.starts_with("dashBar")) return !features.dashed_bars;
    if (name == "lyricsStackingOrder") return !features.lyrics || !features.dynamics;
    if (name == "lyricsAutoCenterOnGrandStaff") return !features.lyrics || !features.grand_staff;
    if (name == "lyricsAutoCenterOnVocalStaves") return !features.lyrics || !features.vocal_staves;
    if (name == "dynamicsHairpinsAutoCenterOnVocalStaves") return !features.dynamics || !features.vocal_staves;
    if (name == "maskSlurs") return !features.slurs || !style.has_explicit_value(Sid::MASK_SLURS);
    if (name == "maskTies") return !features.ties || !style.has_explicit_value(Sid::MASK_TIES);
    return false;
}

void convert_style(pugi::xml_node score_node, Score &score, std::optional<ElementId> score_id, const ScoreFeatures &features,
                   std::vector<ExportWarning> &warnings) {
    // The native writer can omit excerpt properties that match the master.
    // Write the effective style so the changed legacy defaults are explicit.
    muse::ByteArray data;
    muse::io::Buffer buffer(&data);
    buffer.open(muse::io::IODevice::WRITE_ONLY);
    if (!score.style().write(&buffer)) throw std::runtime_error("could not serialize score style");
    buffer.close();
    charge_xml(data.size());
    pugi::xml_document xml;
    if (!xml.load_buffer(data.const_data(), data.size(), pugi::parse_default | pugi::parse_ws_pcdata))
        throw std::runtime_error("invalid style");
    auto style = xml.child("museScore").child("Style");
    std::array<bool, std::size(supported_styles)> seen{};
    for (auto child = style.first_child(); child;) {
        poll();
        const auto next = child.next_sibling();
        if (child.type() == pugi::node_element) {
            const std::string_view name = child.name();
            const auto *known = find_style(name);
            if (!known) {
                unsupported(score_node, "style " + std::string(name), score_id, warnings);
            } else if (std::exchange(seen[known - std::begin(supported_styles)], true)) {
                unsupported(score_node, "duplicate style " + std::string(name), score_id, warnings);
            } else if (name == "defaultsVersion") {
                child.text().set("470");
            } else if (!known->legacy) {
                if (!five_only_style_is_inactive(name, features, score.style()) && !style_matches(child, *known))
                    unsupported(score_node, "style " + std::string(name), score_id, warnings);
                style.remove_child(child);
            }
        }
        child = next;
    }
    if (!style.child("defaultsVersion")) style.prepend_child("defaultsVersion").text().set("470");
    if (features.force_names && score.visible_part_count() == 1) style.child("hideInstrumentNameIfOneInstrument").text().set(false);
    if (auto old = score_node.child("Style")) score_node.remove_child(old);
    score_node.prepend_copy(style);
}

void convert_notation(pugi::xml_node node, const Score &score, std::optional<ElementId> score_id, ScoreFeatures &features,
                      ParenthesisAliases &aliases, std::vector<ExportWarning> &warnings) {
    poll();
    const std::string_view name = node.name();
    const std::string_view parent = node.parent().name();
    features.lyrics |= name == "Lyrics";
    features.slurs |= one_of(name, {"Slur", "HammerOnPullOff"});
    features.ties |= one_of(name, {"Tie", "PartialTie", "LaissezVib"});
    features.dynamics |= one_of(name, {"Dynamic", "Expression", "HairPin"}) ||
                         (name == "Spanner" && std::string_view(node.attribute("type").value()) == "Pedal");
    features.dashed_bars |= name == "BarLine" && std::string_view(node.child_value("subtype")) == "dashed";

    if (name == "Chord" && node.child("NoteParenGroup")) {
        convert_note_indices(node, score, score_id, aliases, warnings);
    } else if (name == "Spanner") {
        if (!is_legacy_connector(node.attribute("type").value(), parent) || node.first_attribute().next_attribute())
            unsupported(node, "Spanner type or attributes", score_id, warnings);
    } else if (one_of(name, {"rootCase", "bassCase"}) && parent == "Harmony") {
        constexpr std::array cases{"auto"sv, "capital"sv, "lower"sv, "upper"sv};
        const auto value = std::find(cases.begin(), cases.end(), node.child_value());
        if (value == cases.end())
            unsupported(node, "Harmony/" + std::string(name), score_id, warnings);
        else
            node.text().set(static_cast<int>(value - cases.begin()) - 1);
    } else if (name == "subtype" && one_of(parent, {"TremoloSingleChord", "TremoloTwoChord"}) &&
               one_of(node.child_value(), {"r128", "r256", "c128", "c256"})) {
        unsupported(node, std::string(parent) + " subtype " + node.child_value(), score_id, warnings);
    } else if (one_of(name, {"InstrumentChange", "StaffState"}) && node.child("Instrument")) {
        const auto *object = source_item(node, score);
        if (object && object->is_instrument_change()) {
            const auto *change = static_cast<const InstrumentChange *>(object);
            convert_instrument(node.child("Instrument"), *change->instrument(), *change->part(), change->tick(), score_id, warnings);
        } else if (object && object->is_staff_state()) {
            const auto *state = static_cast<const StaffState *>(object);
            convert_instrument(node.child("Instrument"), *state->instrument(), *state->part(), state->tick(), score_id, warnings);
        } else {
            unsupported(node, std::string(name) + "/Instrument", score_id, warnings);
        }
    }

    unsigned fragment_index = 0;
    for (auto child = node.first_child(); child;) {
        poll();
        const auto next = child.next_sibling();
        const std::string_view field = child.name();
        if (child.type() == pugi::node_element && !one_of(field, {"Score", "Style"})) {
            const bool note_endpoint = name == "Note" && (child.child("startElement") || child.child("endElement"));
            if (note_endpoint || field == "Image" || !allowed_child(node, field)) {
                unsupported(child, std::string(name) + "/" + std::string(field), score_id, warnings);
            } else if (name == "Staff" && field == "BracketItem") {
                convert_bracket(child, score_id, warnings);
            } else if (field == "maskSlurTie" || (name == "ChordLine" && one_of(field, {"o1", "o2", "o3", "o4"})) ||
                       (name == "TremoloTwoChord" && field == "StemDirection")) {
                unsupported(child, std::string(name) + "/" + std::string(field), score_id, warnings);
            } else if ((name == "Harmony" && field == "excludeVerticalAlign") ||
                       (name == "MeasureRepeat" && field == "measureRepeatNumberOffset")) {
                if (std::string_view(child.child_value()) == "false" || child.text().as_double(1.0) == 0.0)
                    node.remove_child(child);
                else
                    unsupported(child, std::string(name) + "/" + std::string(field), score_id, warnings);
            } else if (one_of(name, {"Beam", "TremoloTwoChord"}) && field == "Fragment") {
                // The current writer marks only fragments for the opposite direction.
                if (child.attribute("direction")) {
                    node.remove_child(child);
                } else {
                    if (const auto ordinal = child.attribute("no");
                        ordinal && ordinal.as_uint(std::numeric_limits<unsigned>::max()) != fragment_index)
                        unsupported(child, "nonconsecutive Beam/Fragment overrides", score_id, warnings);
                    child.remove_attribute("no");
                    ++fragment_index;
                }
            } else if (name == "StaffType" && one_of(field, {"StaffLabel", "instrumentLabelVisibility"})) {
                if (parent == "StaffTypeChange")
                    unsupported(child, "StaffTypeChange/StaffType/" + std::string(field), score_id, warnings);
                else
                    node.remove_child(child);
            } else {
                convert_notation(child, score, score_id, features, aliases, warnings);
            }
        }
        child = next;
    }
}

thread_local std::optional<ExportWarning> warning_identity_test_fault;

bool valid_tie_locator(std::string_view id) {
    for (const auto prefix : {"locator:score:", "measure:", "tick:", "track:", "note:"}) {
        if (!id.starts_with(prefix)) return false;
        id.remove_prefix(std::string_view(prefix).size());
        const auto slash = id.find('/');
        if (slash == std::string_view::npos || slash == 0 || id.substr(0, slash).find_first_not_of("0123456789") != std::string_view::npos)
            return false;
        id.remove_prefix(slash + 1);
    }
    return id == "tieFor";
}

void normalize_warnings(std::vector<ExportWarning> &warnings) {
    std::vector<ExportWarning> unique;
    for (auto &w : warnings) {
        if (!w.object || w.object->kind.empty() || w.object->id.empty()) throw std::invalid_argument("4.70 source warning has no identity");
        const auto &id = w.object->id;
        bool valid = (w.object->kind == "tie" && valid_tie_locator(id)) || (w.object->kind == "request" && id.starts_with("version:"));
        if (w.object->kind == "page_lock") {
            const auto separator = id.find("..");
            valid = separator != std::string::npos && element_id_from_string(id.substr(0, separator)) &&
                    element_id_from_string(id.substr(separator + 2));
        } else if (w.object->kind == "group_bracket") {
            const auto separator = id.find(':');
            valid = separator != std::string::npos && element_id_from_string(id.substr(0, separator)) && separator + 1 < id.size() &&
                    id.find_first_not_of("0123456789", separator + 1) == std::string::npos;
        } else
            valid = valid || element_id_from_string(id).has_value();
        if (!valid) throw std::invalid_argument("4.70 source warning has an invalid identity");
        if (w.code == "B470_UNSUPPORTED_FEATURE") w.message = "Cannot write 4.70: the source feature has no defined downgrade.";
        const auto same = [&](const ExportWarning &v) {
            return v.code == w.code && v.message == w.message && v.object && w.object && v.object->kind == w.object->kind &&
                   v.object->id == w.object->id;
        };
        if (std::none_of(unique.begin(), unique.end(), same)) unique.push_back(std::move(w));
    }
    warnings = std::move(unique);
}

// Keep authored whitespace in rich text while exposing structural children to the connector checks.
void remove_xml_indentation(pugi::xml_node node) {
    poll();
    if (one_of(node.name(), {"text", "longName", "shortName", "transposition"})) return;
    for (auto child = node.first_child(); child;) {
        const auto next = child.next_sibling();
        if (child.type() == pugi::node_element)
            remove_xml_indentation(child);
        else if (child.type() == pugi::node_pcdata && node.first_child() != node.last_child() &&
                 std::string_view(child.value()).find_first_not_of(" \t\r\n") == std::string_view::npos)
            node.remove_child(child);
        child = next;
    }
}

ExportWarning instrument_group_warning(std::string part_eid) {
    return {"B470_INSTRUMENT_GROUP_NAME_DROPPED", "Instrument group-name override was removed.",
            ExportWarningObject{"part", std::move(part_eid)}};
}

std::string instrument_owner_id(pugi::xml_node instrument, const Score &score) {
    const auto owner = instrument.parent();
    if (std::string_view(owner.name()) == "Part") return owner.child_value("eid");
    const auto *item = source_item(owner, score);
    if (item && item->is_instrument_change()) return static_cast<const InstrumentChange *>(item)->part()->eid().to_std_string();
    if (item && item->is_staff_state()) return static_cast<const StaffState *>(item)->part()->eid().to_std_string();
    throw std::invalid_argument("4.70 instrument label has no owning part");
}

void convert_degradations(pugi::xml_node node, const Score &score, std::vector<ExportWarning> &warnings) {
    for (auto child = node.first_child(); child;) {
        poll();
        auto next = child.next_sibling();
        const std::string_view name = child.name();
        bool remove = false;
        if (name == "SharedPart") {
            warnings.push_back({"B470_SHARED_PART_DROPPED",
                                "Shared-part mapping was removed; its staves and content were retained as ordinary parts.",
                                ExportWarningObject{"shared_part", child.child_value("eid")}});
            child.set_name("Part");
            child.remove_child("sharedPartEnabled");
        } else if (name == "sharedPart")
            remove = true;
        else if (name == "StaveSharingLabel") {
            warnings.push_back({"B470_STAVE_SHARING_LABEL_DROPPED", "Stave-sharing label was removed.", source_object(child, {})});
            remove = true;
        } else if (name == "PageLocks") {
            for (auto lock : child.children("pageLock")) {
                poll();
                warnings.push_back({"B470_PAGE_LOCK_DROPPED", "Page lock was removed.",
                                    ExportWarningObject{"page_lock", std::string(lock.child_value("startMeasure")) + ".." +
                                                                         lock.child_value("endMeasure")}});
            }
            remove = true;
        } else if (name == "BracketItem" && std::string_view(child.child_value("type")) == "Group") {
            warnings.push_back(
                {"B470_GROUP_BRACKET_DROPPED", "Group bracket was removed.",
                 ExportWarningObject{"group_bracket", std::string(node.child_value("eid")) + ":" + child.child_value("level")}});
            remove = true;
        } else if (name == "InstrumentLabel") {
            bool changed = false;
            for (const char *field : {"allowGroupName", "customNameLongGroup", "customNameShortGroup", "useCustomGroupName"})
                changed = child.remove_child(field) || changed;
            if (changed) warnings.push_back(instrument_group_warning(instrument_owner_id(node, score)));
        }
        if (remove)
            node.remove_child(child);
        else
            convert_degradations(child, score, warnings);
        child = next;
    }
}

void warn_active_instrument_groups(const Score &score, std::vector<ExportWarning> &warnings) {
    const auto enabled = [&](const String &group) {
        const Sid sid = (group == "woodwinds" || group == "brass") ? Sid::WINDS_NAME_BY_GROUP :
                        group == "vocals"                          ? Sid::VOCALS_NAME_BY_GROUP :
                        group == "strings"                         ? Sid::STRINGS_NAME_BY_GROUP :
                                                                     Sid::OTHERS_NAME_BY_GROUP;
        return score.style().style_b(sid);
    };
    std::vector<int> ticks{0};
    for (const auto *part : score.parts()) {
        for (const auto &[tick, instrument] : part->instruments()) {
            poll();
            if (tick > 0) ticks.push_back(tick);
        }
    }
    std::sort(ticks.begin(), ticks.end());
    ticks.erase(std::unique(ticks.begin(), ticks.end()), ticks.end());
    std::vector<bool> grouped(score.parts().size(), false);
    for (const auto tick : ticks) {
        const Instrument *previous = nullptr;
        std::size_t previous_index = 0;
        for (std::size_t index = 0; index < grouped.size(); ++index) {
            poll();
            const auto *part = score.parts()[index];
            const auto *instrument = part->instrument(mu::engraving::Fraction::from_ticks(tick));
            const auto &label = instrument->instrument_label();
            if (part->is_shared_part() || !label.allow_group_name()) {
                previous = nullptr;
                continue;
            }
            if (!part->show() || part->visible_staves_count() == 0) continue;
            if (previous && previous->id() == instrument->id() && enabled(instrument->group())) {
                grouped[previous_index] = true;
                grouped[index] = true;
            }
            previous = instrument;
            previous_index = index;
        }
    }
    for (std::size_t index = 0; index < grouped.size(); ++index) {
        if (grouped[index]) warnings.push_back(instrument_group_warning(score.parts()[index]->eid().to_std_string()));
    }
}

Result<ExportOutput> refused(std::vector<ExportWarning> warnings) {
    Error error{ErrorCode::UNSUPPORTED, "this score contains content the 4.70 writer cannot yet convert"};
    for (auto &warning : warnings) {
        error.message += "\n" + warning.message;
        if (warning.code == "B470_UNSUPPORTED_FEATURE")
            warning.message = "Cannot write 4.70: the source feature has no defined downgrade.";
        else if (warning.code == "B470_SHARED_PART_DROPPED")
            warning.message = "Shared-part mapping was removed; its staves and content were retained as ordinary parts.";
        else if (warning.code == "B470_PAGE_LOCK_DROPPED")
            warning.message = "Page lock was removed.";
        else if (warning.code == "B470_GROUP_BRACKET_DROPPED")
            warning.message = "Group bracket was removed.";
        else if (warning.code == "B470_STAVE_SHARING_LABEL_DROPPED")
            warning.message = "Stave-sharing label was removed.";
    }
    normalize_warnings(warnings);
    error.export_warnings = std::move(warnings);
    return std::unexpected(std::move(error));
}

