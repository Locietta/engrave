Result<ExportOutput> export_score(const music::EngineContext& context, const music::ScoreProject& project,
                                  Score& score, const std::string& format, const music::ExportOptions& options) {
    std::vector<ExportWarning> warnings;
    const auto score_id = score.eid().isValid() ? std::optional(from_engine(score.eid())) : std::nullopt;
    if (!score.isMaster()) {
        warnings.push_back({export_warning_code::excerpt, "4.70 export of an excerpt is not implemented", score_id});
        return refused(std::move(warnings));
    }
    auto& master = static_cast<MasterScore&>(score);
    if (master.chordList()->customChordList() && !master.chordList()->empty())
        warnings.push_back({export_warning_code::custom_chord_list, "4.70 conversion of a custom chord list is not implemented", score_id});
    if (const auto automation = master.automationData()) {
        for (const auto& [key, curve] : automation->curves()) {
            (void)key;
            if (std::any_of(curve.begin(), curve.end(), [](const auto& point) { return !point.second.generated; }))
                warnings.push_back({export_warning_code::automation, "4.70 cannot represent this automation curve", score_id});
        }
    }

    // The 5.00 serializer supplies the current DOM values. It is only an
    // intermediate: the checked subset is converted to the 4.70 structure.
    // Its XML is working data, not the output, so do not apply the output cap.
    auto* budget = muse::io::activeWriteBudget;
    struct RestoreOutputLimit {
        muse::io::WriteBudget* budget;
        std::optional<std::uint64_t> limit;
        ~RestoreOutputLimit() { if (budget) budget->output = limit; }
    } restore{budget, budget ? budget->output : std::nullopt};
    if (budget) budget->output.reset();
    const std::string source = music::export_native_score(context, project, "mscx", options, {});
    muse::ByteArray style_data;
    muse::io::Buffer style_buffer(&style_data);
    style_buffer.open(muse::io::IODevice::WriteOnly);
    if (!score.style().write(&style_buffer)) throw std::runtime_error("could not serialize score style");
    style_buffer.close();
    if (budget) budget->output = restore.limit;

    charge_xml(source.size() + style_data.size());
    pugi::xml_document xml, style_xml;
    if (!xml.load_buffer(source.data(), source.size())
        || !style_xml.load_buffer(style_data.constData(), style_data.size()))
        throw std::runtime_error("could not parse the engine's score or style output");
    auto root = xml.child("museScore");
    auto score_node = root.child("Score");
    auto style = style_xml.child("museScore").child("Style");
    if (!root || !score_node || !style) throw std::runtime_error("engine output has no score or style");
    inspect_features(root, {}, warnings);
    inspect(root, "museScore", {}, warnings);

    std::size_t style_count = 0, unique_styles = 0;
    std::array<bool, std::size(supported_styles)> seen_styles{};
    for (auto child = style.first_child(); child;) {
        poll();
        const auto next = child.next_sibling();
        if (child.type() != pugi::node_element) { child = next; continue; }
        const std::string_view name = child.name();
        ++style_count;
        const auto* known = find_style(name);
        // Only values covered by the 4.70 control are accepted in this slice.
        // In particular a 5.00 default can differ from 4.70 behavior.
        if (!known || !style_matches(child, *known)) {
            warnings.push_back({export_warning_code::unsupported_style, "4.70 conversion is not implemented for style " + std::string(name), score_id});
        }
        if (known) {
            const auto index = static_cast<std::size_t>(known - std::begin(supported_styles));
            if (seen_styles[index])
                warnings.push_back({export_warning_code::unsupported_style, "4.70 conversion encountered a duplicate style " + std::string(name), score_id});
            else { seen_styles[index] = true; ++unique_styles; }
        }
        if (name == "defaultsVersion" && known) {
            child.text().set("470");
        } else if (known && !known->legacy) {
            style.remove_child(child);
        }
        child = next;
    }
    if (style_count != std::size(supported_styles) || unique_styles != std::size(supported_styles))
        warnings.push_back({export_warning_code::unsupported_style, "4.70 conversion is not implemented for this style catalog", score_id});
    if (!warnings.empty()) return refused(std::move(warnings));

    // 5.00 wraps instrument names in InstrumentLabel, while 4.70 reads them
    // directly in Instrument. It also stores the part name on Part itself.
    auto part = score_node.child("Part");
    for (const Part* source_part : score.parts()) {
        if (!part) throw std::runtime_error("part count changed during serialization");
        auto first_instrument = part.child("Instrument");
        if (!first_instrument) throw std::runtime_error("serialized part has no instrument");
        for (auto instrument = first_instrument; instrument; instrument = instrument.next_sibling("Instrument")) {
            if (auto label = instrument.child("InstrumentLabel")) {
                for (const auto name : label.children())
                    if (name.type() == pugi::node_element) instrument.insert_copy_before(name, label);
                instrument.remove_child(label);
            }
        }
        auto legacy_track_name = part.insert_child_before("trackName", first_instrument);
        legacy_track_name.text().set(source_part->partName().toStdString().c_str());
        if (auto eid = part.child("eid")) {
            warnings.push_back({export_warning_code::part_identity_omitted, "4.70 cannot persist a part's 5.00 element id",
                                element_id_from_string(eid.child_value())});
            part.remove_child(eid);
        }
        part = part.next_sibling("Part");
    }
    if (part) throw std::runtime_error("part count changed during serialization");
    if (auto old = score_node.child("Style")) score_node.remove_child(old);
    score_node.prepend_copy(style);
    root.attribute("version").set_value("4.70");

    muse::ByteArray xml_data;
    // For MSCX this is the final output, so enforce its cap as it grows. For
    // MSCZ the XML is an intermediate and only the compressed archive is capped.
    OutputBuffer xml_buffer(&xml_data, format == "mscx");
    xml_buffer.open(muse::io::IODevice::WriteOnly);
    XmlOutput writer(xml_buffer);
    xml.save(writer, "  ", pugi::format_default, pugi::encoding_utf8);
    xml_buffer.close();
    muse::ByteArray data;
    if (format == "mscx") {
        if (budget && !budget->outputSize(xml_data.size())) throw muse::io::WriteBudgetStop{};
        data = std::move(xml_data);
    } else {
        OutputBuffer output(&data);
        output.open(muse::io::IODevice::WriteOnly);
        MscWriter::Params params;
        params.device = &output;
        params.mainFileName = u"score.mscx";
        MscWriter archive(params);
        if (!archive.open()) throw std::runtime_error("could not open 4.70 archive writer");
        archive.writeScoreFile(xml_data);
        archive.close();
        if (archive.hasError()) throw std::runtime_error("could not write 4.70 archive");
        output.close();
    }
    const auto* first = reinterpret_cast<const std::byte*>(data.constData());
    return ExportOutput{std::vector<std::byte>(first, first + data.size()), std::move(warnings)};
}

